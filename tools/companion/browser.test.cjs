    await page.locator('#message').fill('A draft that survives navigation');
    await go('Memory');
    await page.getByRole('button', { name: 'Add a memory', exact: true }).click();
    await page.getByLabel('Something worth remembering').fill('<img src=x onerror=alert(1)> Coffee before meetings.');
    await page.getByRole('button', { name: 'Save memory', exact: true }).click();
    assert.match(await page.locator('#collection-results').textContent(), /<img src=x/);
    assert.equal(await page.locator('#collection-results img').count(), 0);
    await page.getByLabel('Search memories').fill('Coffee before');
