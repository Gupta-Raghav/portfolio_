    await axe('memory');
    await page.screenshot({ path: path.join(output, 'desktop-memory.png'), fullPage: true });
    await go('Chat');
    assert.equal(await page.locator('#message').inputValue(), 'A draft that survives navigation');
    await page.getByRole('button', { name: /Raghav’s space/ }).click();
    await axe('profile chooser');
    await page.getByRole('button', { name: /Guest Step into this space/ }).click();
    assert.equal(await page.locator('.message').count(), 0);
    await go('Memory');
    assert.doesNotMatch(await page.locator('#collection-results').textContent(), /A walk before work/);
    await page.getByRole('button', { name: /Guest’s space/ }).click();
    await page.getByRole('button', { name: /Raghav Step into this space/ }).click();
    await page.locator('.recent-chat').first().click();
    assert.equal(await page.locator('.message').count(), 2);
    assert.equal(await page.locator('#message').inputValue(), 'A draft that survives navigation');
    await go('Artifacts');
    await axe('artifacts');
    await page.screenshot({ path: path.join(output, 'desktop-artifacts.png'), fullPage: true });
    await page.getByRole('button', { name: 'Save The art of a slower weekend', exact: true }).click();
    await page.getByRole('button', { name: 'Saved', exact: true }).click();
    assert.equal(await page.locator('.artifact-card').count(), 1);
    await page.locator('.artifact-open').first().click();
    await axe('artifact reader');
    const downloadEvent = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download note', exact: true }).click();
    const download = await downloadEvent;
    assert.match(download.suggestedFilename(), /slower-weekend.md$/);
    await download.saveAs(path.join(output, download.suggestedFilename()));
    await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
    await page.getByRole('button', { name: 'New note', exact: true }).click();
